import {test,expect} from '@playwright/test';
test('自然周、月历、规则保存与不可约拦截',async({page})=>{
 await page.clock.setFixedTime(new Date('2026-11-11T12:00:00+08:00'));
 await page.goto('/');
 await page.screenshot({path:`test-results/calendar-${test.info().project.name}.png`,fullPage:true});
 await page.getByRole('button',{name:'周',exact:true}).click();
 await expect(page.locator('.board-head button').first()).toHaveAttribute('aria-label','查看 2026-11-09 课表');
 await expect(page.locator('.timeline-column')).toHaveCount(7);
 await page.screenshot({path:`test-results/week-${test.info().project.name}.png`,fullPage:true});
 await page.getByRole('button',{name:'下一日或周'}).click();
 await expect(page.locator('.board-head button').first()).toHaveAttribute('aria-label','查看 2026-11-16 课表');
 await page.getByRole('button',{name:'月',exact:true}).click();
 await page.getByLabel('选择月份').fill('2026-12');
 await expect(page.locator('.month-grid button')).toHaveCount(42);
 await page.getByRole('button',{name:'2026-12-02 0 节课程',exact:true}).click();
 await expect(page.getByLabel('选择日期')).toHaveValue('2026-12-02');
 await page.getByRole('link',{name:'时间设置',exact:true}).click();
 await page.getByLabel('我的工作时间 1 开始',{exact:true}).fill('10:00');
 await page.getByLabel('课程间隔',{exact:true}).selectOption('15');
 await page.getByRole('button',{name:'添加',exact:true}).click();
 await page.getByLabel('不可预约 1 开始',{exact:true}).fill('2026-12-02T12:00');
 await page.getByLabel('不可预约 1 结束',{exact:true}).fill('2026-12-02T14:00');
 await page.getByRole('button',{name:'保存设置',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('已保存');
 await page.reload();await expect(page.getByLabel('课程间隔',{exact:true})).toHaveValue('15');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:`test-results/settings-${test.info().project.name}.png`,fullPage:true});
 await page.goto('/#/'); await page.getByRole('button',{name:'排课',exact:true}).click();
 await page.getByLabel('上课日期',{exact:true}).fill('2026-12-02');
 await page.getByLabel('开始时间',{exact:true}).fill('09:00');
 await expect(page.getByRole('alert')).toContainText('可预约时间');
 await page.getByLabel('开始时间',{exact:true}).fill('12:00');
 await expect(page.getByRole('alert')).toContainText('不可预约');
 await expect(page.getByRole('button',{name:'确认排课',exact:true})).toBeDisabled();
 await page.getByLabel('开始时间',{exact:true}).fill('14:00');
 await page.getByRole('button',{name:'确认排课',exact:true}).click();
 await expect(page.locator('.timeline-booking')).toHaveCount(1);
 await page.goto('/#/'); await page.getByRole('button',{name:'排课',exact:true}).click();
 await page.getByLabel('上课日期',{exact:true}).fill('2026-12-02');
 await page.getByLabel('开始时间',{exact:true}).fill('15:00');
 await expect(page.getByRole('alert')).toContainText('间隔 15');
 await page.getByLabel('开始时间',{exact:true}).fill('15:15');
 await expect(page.getByRole('button',{name:'确认排课',exact:true})).toBeEnabled();
});

