import {test,expect} from '@playwright/test';

test('新增学员、三节排课、改期取消、筛选与档案持久化',async({page})=>{
 await page.clock.setFixedTime(new Date('2026-11-11T10:30:00+08:00'));
 await page.goto('/');
 await page.getByRole('link',{name:'添加学员',exact:true}).click();
 await page.getByLabel('姓名',{exact:true}).fill('徐安');
 await page.getByLabel('联系电话', {exact:false}).fill('138 1234 5678');
 await page.getByRole('button',{name:'普拉提',exact:true}).click();
 await page.getByLabel('备注', {exact:false}).fill('训练时留意肩部活动范围');
 await page.screenshot({path:`test-results/student-form-${test.info().project.name}.png`,fullPage:true});
 await page.getByRole('button',{name:'添加学员',exact:true}).click();
 await expect(page.locator('.profile-header h2')).toHaveText('徐安');
 await expect(page.getByRole('status')).toContainText('学员已添加');
 const studentUrl=page.url();const bookingUrls:string[]=[];
 for(const [date,start] of [['2026-11-12','09:00'],['2026-11-13','10:00'],['2026-11-14','11:00']]){
  await page.goto(studentUrl);
  await page.getByRole('link',{name:'为 TA 排课',exact:false}).click();
  await expect(page.getByRole('combobox',{name:'学员',exact:true}).locator('option:checked')).toHaveText('徐安');
  await expect(page.getByRole('combobox',{name:'课程类型',exact:true}).locator('option:checked')).toHaveText('普拉提');
  await page.getByLabel('上课日期',{exact:true}).fill(date!);
  await page.getByLabel('开始时间',{exact:true}).fill(start!);
  await page.getByRole('button',{name:'确认排课',exact:true}).click();
  await expect(page.locator('.timeline-booking')).toContainText('徐安');
  await page.locator('.timeline-booking').click();bookingUrls.push(page.url());
 }
 await page.goto(bookingUrls[0]!);
 await page.getByLabel('开始时间',{exact:true}).fill('10:00');
 await page.getByRole('button',{name:'保存修改',exact:true}).click();
 await expect(page.locator('.timeline-booking')).toContainText('10:00');
 await page.goto(bookingUrls[1]!);page.once('dialog',dialog=>dialog.accept());
 await page.getByRole('button',{name:'取消预约',exact:true}).click();
 await page.goto(studentUrl);
 await expect(page.getByTestId('student-active')).toHaveText('2 节');
 await expect(page.locator('.course-history-row')).toHaveCount(3);
 await page.getByRole('button',{name:'已预约',exact:true}).click();
 await expect(page.locator('.course-history-row')).toHaveCount(2);
 await page.getByRole('button',{name:'已取消',exact:true}).click();
 await expect(page.locator('.course-history-row')).toHaveCount(1);
 await page.getByRole('button',{name:'筛选课程',exact:true}).click();
 await page.getByLabel('筛选开始日期').fill('2026-11-13');
 await page.getByLabel('筛选结束日期').fill('2026-11-13');
 await expect(page.locator('.course-history-row')).toHaveCount(1);
 await page.getByLabel('筛选课程类型').selectOption({label:'力量训练'});
 await expect(page.locator('.course-history-row')).toHaveCount(0);
 await page.getByLabel('筛选课程类型').selectOption({label:'普拉提'});
 await expect(page.locator('.course-history-row')).toHaveCount(1);
 await page.getByLabel('筛选结束日期').fill('2026-11-12');
 await expect(page.getByRole('alert')).toContainText('结束日期');
 await page.getByRole('link',{name:'编辑学员',exact:true}).click();
 await page.getByLabel('姓名',{exact:true}).fill('徐安安');
 await page.getByRole('button',{name:'保存学员',exact:true}).click();
 await page.reload();
 await expect(page.locator('.profile-header h2')).toHaveText('徐安安');
 await expect(page.getByRole('link',{name:'13812345678',exact:true})).toHaveAttribute('href','tel:13812345678');
 await expect(page.getByTestId('student-active')).toHaveText('2 节');
 await expect(page.locator('.course-history-row')).toHaveCount(3);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:`test-results/student-profile-${test.info().project.name}.png`,fullPage:true});
 await page.goto('/#/students');
 await page.getByLabel('搜索学员').fill('138 1234');
 await expect(page.locator('.student-row')).toHaveCount(1);
 await page.screenshot({path:`test-results/students-list-${test.info().project.name}.png`,fullPage:true});
});

test('今日概览、下一节、确认与完成实时刷新',async({page})=>{
 await page.clock.setFixedTime(new Date('2026-11-11T10:30:00+08:00'));
 await page.goto('/');
 await expect(page.getByTestId('today-count')).toHaveText('4');
 await expect(page.getByTestId('month-completed')).toHaveText('0');
 await expect(page.locator('.next-lesson')).toContainText('陈宇');
 await expect(page.locator('.next-lesson')).toContainText('11:00');
 await page.screenshot({path:`test-results/workbench-${test.info().project.name}.png`,fullPage:true});
 await page.locator('.work-items > summary').click();
 const past=page.locator('.work-item').filter({hasText:'林晓'});
 await past.getByRole('button',{name:'完成',exact:true}).click();
 await expect(page.getByTestId('month-completed')).toHaveText('1');
 await expect(past).toHaveCount(0);
 const pending=page.locator('.work-item').filter({hasText:'王可欣'});
 await pending.getByRole('button',{name:'确认',exact:true}).click();
 await expect(pending).toHaveCount(0);
 await page.reload();
 await expect(page.getByTestId('month-completed')).toHaveText('1');
 await expect(page.locator('.pending-dot')).toHaveCount(0);
 await page.getByRole('link',{name:'查看下一节课程',exact:true}).click();
 await expect(page.getByRole('combobox',{name:'学员',exact:true}).locator('option:checked')).toHaveText('陈宇');
 await page.getByRole('button',{name:'返回课表',exact:false}).click();
 await page.getByRole('button',{name:'周',exact:true}).click();
 await page.getByLabel('选择日期').fill('2026-11-19');
 await page.locator('.overview-today').click();
 await expect(page.getByLabel('选择日期')).toHaveValue('2026-11-11');
 await expect(page.getByRole('button',{name:'日',exact:true})).toHaveAttribute('aria-pressed','true');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});

